"""Generate Prometheus recording rules and collector processors from normalization mappings.

python -m normalize.generate          # write generated files
python -m normalize.generate --check  # exit 1 if generated files are stale (CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

from normalize.schema import Mapping, Metric, Source, load_mapping

ROOT = Path(__file__).resolve().parent.parent
HEADER = "# GENERATED by normalize/generate.py from {src} — do not edit by hand.\n"

# mapping file -> (prometheus rules output, collector processors output)
TARGETS: dict[str, tuple[str, str]] = {
    "normalize/gpu.yaml": ("prometheus/rules/gpu-normalized.yaml", "collector/generated/gpu-transform.yaml"),
    "normalize/engine_vllm.yaml": (
        "prometheus/rules/engine-normalized.yaml",
        "collector/generated/engine-transform.yaml",
    ),
}


def _num(value: float) -> str:
    return str(int(value)) if value.is_integer() else repr(value)


def _selector(source: Source) -> str:
    if not source.selector:
        return source.metric
    matchers = ",".join(f'{k}="{v}"' for k, v in sorted(source.selector.items()))
    return f"{source.metric}{{{matchers}}}"


def _relabel(expr: str, label_map: dict[str, str]) -> str:
    for src, dst in label_map.items():
        if src != dst:
            expr = f'label_replace({expr}, "{dst}", "$1", "{src}", "(.*)")'
    return expr


def prometheus_rules(mapping: Mapping) -> dict[str, Any]:
    rules: list[dict[str, Any]] = []
    for metric in mapping.metrics:
        for vendor, source in metric.sources.items():
            if source is None:
                continue
            base = _selector(source)
            labels = {mapping.discriminator_label: vendor}
            if source.kind == "bitmask":
                for bit, reason in sorted(source.reasons.items()):
                    expr = _relabel(f"floor({base} / {2**bit}) % 2", mapping.labels[vendor])
                    rules.append(
                        {
                            "record": mapping.prom_name(metric),
                            "expr": expr,
                            "labels": {**labels, "reason": reason},
                        }
                    )
                continue
            if source.kind == "histogram":
                for suffix in ("_bucket", "_sum", "_count"):
                    src = Source(metric=source.metric + suffix, selector=source.selector)
                    rules.append(
                        {
                            "record": mapping.prom_name(metric) + suffix,
                            "expr": _relabel(_selector(src), mapping.labels[vendor]),
                            "labels": dict(labels),
                        }
                    )
                continue
            scaled = base if source.scale == 1.0 else f"{base} * {_num(source.scale)}"
            rules.append(
                {
                    "record": mapping.prom_name(metric),
                    "expr": _relabel(scaled, mapping.labels[vendor]),
                    "labels": labels,
                }
            )
    return {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {
            "name": f"{mapping.namespace}-normalized",
            "labels": {"release": "kube-prometheus-stack", "app.kubernetes.io/part-of": "observe-d"},
        },
        "spec": {"groups": [{"name": f"{mapping.namespace}-normalized", "rules": rules}]},
    }


def _otel_target_name(mapping: Mapping, metric: Metric, source: Source) -> str:
    # The collector cannot expand bitmasks; it ships the raw value and SQL expands it with bitTest().
    suffix = "_bitmask" if source.kind == "bitmask" else ""
    return f"{mapping.otel_name(metric)}{suffix}"


def collector_processors(mapping: Mapping) -> dict[str, Any]:
    transforms: list[dict[str, Any]] = []
    for metric in mapping.metrics:
        if not metric.clickhouse:
            continue
        for vendor, source in metric.sources.items():
            if source is None:
                continue
            operations: list[dict[str, Any]] = [
                {"action": "add_label", "new_label": mapping.discriminator_label, "new_value": vendor}
            ]
            for src, dst in mapping.labels[vendor].items():
                if src != dst:
                    operations.append({"action": "update_label", "label": src, "new_label": dst})
            if source.kind == "value" and source.scale != 1.0:
                operations.append({"action": "experimental_scale_value", "experimental_scale": source.scale})
            transform: dict[str, Any] = {
                "include": source.metric,
                "match_type": "strict",
                # insert (copy) rather than update: one vendor metric may feed several normalized names.
                "action": "insert",
                "new_name": _otel_target_name(mapping, metric, source),
            }
            if source.selector:
                transform["experimental_match_labels"] = dict(sorted(source.selector.items()))
            transform["operations"] = operations
            transforms.append(transform)

    ns = mapping.namespace
    return {
        "processors": {
            f"metrics_transform/{ns}_normalize": {"transforms": transforms},
            # The pipeline using these processors carries only this namespace's exporter;
            # everything not renamed into `<ns>.` is dropped before Kafka.
            f"filter/{ns}_subset": {
                "error_mode": "ignore",
                "metrics": {"metric": [f'not IsMatch(name, "^{ns}\\\\.")']},
            },
        }
    }


def _dump(doc: dict[str, Any], src: str) -> str:
    body = yaml.safe_dump(doc, sort_keys=False, default_flow_style=False, width=1000, allow_unicode=True)
    return HEADER.format(src=src) + body


def render_all(root: Path = ROOT) -> dict[Path, str]:
    out: dict[Path, str] = {}
    for src, (rules_path, collector_path) in TARGETS.items():
        mapping = load_mapping(root / src)
        out[root / rules_path] = _dump(prometheus_rules(mapping), src)
        out[root / collector_path] = _dump(collector_processors(mapping), src)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args(argv)

    stale: list[Path] = []
    for path, content in render_all().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")

    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run: python -m normalize.generate)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
